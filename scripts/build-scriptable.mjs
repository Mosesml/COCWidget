import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const bundle = await build({ entryPoints: ['integrations/scriptable/src/core.ts'], bundle: true, write: false,
  platform: 'neutral', target: 'es2020', format: 'iife', globalName: 'COCWidgetCore', minify: true, legalComments: 'none' });
const adapter = await readFile('integrations/scriptable/src/adapter.js', 'utf8');
const header = '// COCWidget — generated by npm run build:scriptable.\n// Shared parser/catalogue attribution: see THIRD_PARTY.md in Mosesml/COCWidget.\n// No network requests. Village data stays in Scriptable local storage.\n';
await writeFile('integrations/scriptable/COCWidget.js', header + bundle.outputFiles[0].text + '\n' + adapter);
console.log('Built integrations/scriptable/COCWidget.js');
